#!/usr/bin/env python3
"""Rows of the profile table (tab:profile, Table V) and the contrast-variant table (tab:variants, Table II) of the ICDE
copy (review round R5; written 2026-11-10).

Read-only on icde27/analysis/{r5_exact,r5_reliability,r5_uncertainty}.json; writes only
icde27/analysis/r5_table_rows.tex, whose two blocks are pasted into icde27/main.tex (tab:profile and tab:variants);
icde27/analysis/check_icde_numbers.py checks that every row occurs there. Seconds. (Pass 2, 2026-11-11: the profile
table uses the exact-recapture basis of r5_exact.json, and the variant table gains its Exact column.)

    cd ..
    .venv/bin/python 06_pandas_conformance-ICDE/icde27/analysis/r5_tables.py

Profile table, with nested values recaptured exactly (r5_exact.json "exact"): per configuration the clean@E2 DIFF share
(%), the paired DIFF difference against pandas 3.0.6 (points), notebooks with an introduced DIFF (pure definition, known
printed-form artifacts excluded), error-free notebooks, agreeing notebooks (error-free, every scored cell equal at E4
or finer), and the other notebooks by first failure (stop: memory cap, time limit or crash; API: unsupported API or
execution model, for pandas a removed or changed API; Sup.: error on supported API; Inh.: error after an earlier
difference; FireDucks has one other).
Variant table: per engine and pandas version, the cells of the pooled clean@E2 pair and the paired difference pooled, with
equal notebook weights, on strictly clean inputs, without every cell that outputs or reads a printed form, and with
nested values recaptured exactly, with up and down arrows where the 95% interval lies above or below 0, and the outer
bounds of the pooled estimate if matching printed forms may hide differences. Numbers: one decimal, round half up.
"""
import decimal
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "r5_table_rows.tex")
NAMES = {"p15": "pandas 1.5.3", "p30": "pandas 3.0.6", "pyarrow_backend": "pyarrow backend", "modin": "Modin",
         "fireducks": "FireDucks", "bodo": "Bodo", "dask": "Dask"}
SHORT = {"pyarrow_backend": "PA", "modin": "Mo", "fireducks": "FD", "bodo": "Bo", "dask": "Da", "p15": "1.5", "p30": "3.0"}


def q(x, nd=1):
    d = decimal.Decimal(repr(float(x))).quantize(decimal.Decimal(1).scaleb(-nd), rounding=decimal.ROUND_HALF_UP)
    s = str(d)
    return "0.0" if s in ("0.0", "-0.0") else s


def sg(x):
    s = q(x)
    if s == "0.0":
        return "$0.0$"
    return "$%s$" % (s if s.startswith("-") else "+" + s)


def mark(reading):
    return {"more often": "$\\uparrow$", "less often": "$\\downarrow$"}.get(reading, "")


def n(x):
    return "{:,}".format(int(x))


def rows():
    rel = json.load(open(os.path.join(HERE, "r5_reliability.json")))
    unc = json.load(open(os.path.join(HERE, "r5_uncertainty.json")))
    X = json.load(open(os.path.join(HERE, "r5_exact.json")))["exact"]
    prof = []
    for lab in ("p15", "p30", "pyarrow_backend", "modin", "fireducks", "bodo", "dask"):
        camp = "drift" if lab in ("p15", "p30") else "conf_1x"
        diff = X["clean_E2"][lab]["clean_E2_DIFF_share"]
        delta = "--" if camp == "drift" else sg(X["pairs"]["%s-p30" % lab]["diff_pp"])
        nb = X["notebooks"][lab]["introduced_DIFF"]
        N = X["notebooks"][lab]
        D = X["failure_decomposition"][lab]
        api = D.get("unsupported API or execution model", 0) + D.get("API removed or changed by pandas", 0)
        prof.append("%s & %s & %s & %d & %d & %d & %d & %d & %d & %d \\\\" % (
            NAMES[lab], q(100 * diff), delta, nb, N["error_free"], N["agreeing"],
            D.get("memory cap", 0) + D.get("time limit", 0) + D.get("dependency crash", 0) + D.get("native crash", 0),
            api, D.get("error on supported API", 0), D.get("error after an earlier difference", 0)))
    var = []
    for e in ("modin", "fireducks", "pyarrow_backend", "bodo", "dask"):
        for v in ("p15", "p30"):
            k = "%s-%s" % (e, v)
            c = rel["contrasts"][k]
            b = unc["pairs"][k]["bounds_pp"]
            x = X["pairs"][k]
            cells = [sg(c[y]["diff_pp"]) + mark(c[y]["reading"])
                     for y in ("pooled_E2", "notebook_weighted_E2", "pooled_E0", "pooled_E2_certain")]
            cells.append(sg(x["diff_pp"]) + mark(x["reading"]))
            var.append("%s--%s & %s & %s & [%s, %s] \\\\" % (
                SHORT[e], SHORT[v], n(c["pooled_E2"]["cells"]), " & ".join(cells), sg(b[0]), sg(b[1])))
    return prof, var


def main():
    prof, var = rows()
    with open(OUT + ".tmp", "w") as f:
        f.write("% generated by icde27/analysis/r5_tables.py (profile rows, then variant rows)\n")
        f.write("\n".join(prof) + "\n%% ----\n" + "\n".join(var) + "\n")
    os.replace(OUT + ".tmp", OUT)
    print("\n".join(prof))
    print("\n".join(var))


if __name__ == "__main__":
    sys.exit(main())
